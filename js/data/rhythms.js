//   palm – true = celé se hraje s dlaní na kobylce (krátké, tmavé)
//   groove – doporučený groove z grooves.js (bicí a basa, které k rytmu ladí)
//
// Tokeny (jeden znak = jeden krok):
//   D  úhoz dolů přes celý hmat (struny 6 → 1)
//   U  úhoz nahoru, jen horní struny (znějící na strunách 1–4, aspoň tři nejvyšší tóny)
//   d u  totéž slabě
//   C  „chick“: úhoz dolů bez basových strun (bez struny basu a střídavého basu)
//   X  tlumený úhoz dolů („chck“, levá ruka povolí), x tlumený nahoru
//   B  bas = kořen hmatu (shape.bass, jinak nejhlubší tón)
//   A  střídavý bas (shape.alt, jinak bas)
//   p  palec (prstoklad) = bas, slaběji než B
//   i m a  prsty: a = nejvyšší znějící struna, m = druhá, i = třetí nejvyšší;
//          bere se jen z tónů nad basovými strunami (u tříhlasých hmatů se opakují)
//   f  všechny tři prsty najednou (i+m+a, „štípnutí“ akordu)
//   -  držet předchozí, .  nic
//   ^  prefix: přízvuk dalšího tokenu (^D)
